CREATE TABLE IF NOT EXISTS "language" (
    id_language BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name        VARCHAR(255) UNIQUE NOT NULL,
    code        VARCHAR(255) UNIQUE NOT NULL
);

CREATE TABLE IF NOT EXISTS "country" (
    id_country  BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name        VARCHAR(255) UNIQUE NOT NULL,
    id_language BIGINT REFERENCES "language"(id_language),
    created_at  TIMESTAMP WITHOUT TIME ZONE default now()
);
